import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const PHOSPHOR_VERSION = '2.1.1';

// The icon grid, in render order.
const GRID = [
  'star', 'bookmark-simple', 'heart', 'flag', 'lightning', 'triangle',
  'asterisk', 'bell', 'lightbulb', 'shapes', 'squares-four', 'dots-nine',
  'stack', 'database', 'archive', 'copy', 'folder', 'tray', 'calendar',
  'envelope', 'check-square', 'file', 'book-open', 'chat-circle-dots',
  'users', 'terminal-window', 'wrench', 'square', 'egg', 'circle', 'moon',
  'sun', 'planet', 'leaf', 'cloud', 'paw-print', 'basket', 'gift', 'bed',
  'fork-knife', 'barbell', 'airplane', 'music-note', 'palette',
  'video-camera', 'bandaids', 'code', 'baseball', 'map-trifold', 'campfire',
  'pizza', 'skull', 'receipt', 'thumbs-up', 'train',
];

// Grid slot -> upstream fill asset, when a future version renames one.
// Empty today: 2.1.1 has every name above verbatim.
const SOURCE_NAME_OVERRIDES = {};

const REPO = path.join(import.meta.dirname, '..', '..');
const OUT_DIR = path.join(
    REPO, 'overlay/chrome/browser/resources/atrium/phosphor');
const CACHE_DIR = process.env.PHOSPHOR_VENDOR_CACHE ||
    path.join(os.tmpdir(), 'atrium-phosphor-vendor');

function ensurePackage() {
  const pkgDir = path.join(CACHE_DIR, 'package');
  if (fs.existsSync(pkgDir)) {
    return pkgDir;
  }
  fs.mkdirSync(CACHE_DIR, {recursive: true});
  const spec = `@phosphor-icons/core@${PHOSPHOR_VERSION}`;
  console.log(`fetching ${spec}...`);
  execFileSync('npm', ['pack', spec, '--silent'], {cwd: CACHE_DIR});
  const tarball = path.join(
      CACHE_DIR, `phosphor-icons-core-${PHOSPHOR_VERSION}.tgz`);
  execFileSync('tar', ['xzf', tarball], {cwd: CACHE_DIR});
  return pkgDir;
}

// The upstream file is one machine-generated, unnested <svg> per glyph, so a
// tag/attr regex reads it exactly as well as a full XML parser would.
function parseShapeChildren(svgSource) {
  const inner = svgSource.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const shapes = [];
  const tagPattern = /<(path|circle|rect|polygon|ellipse)\b([^>]*?)\/?>/g;
  let match;
  while ((match = tagPattern.exec(inner))) {
    const [, tag, attrSource] = match;
    const attrs = {};
    const attrPattern = /([\w:-]+)="([^"]*)"/g;
    let attrMatch;
    while ((attrMatch = attrPattern.exec(attrSource))) {
      attrs[attrMatch[1]] = attrMatch[2];
    }
    shapes.push([tag, attrs]);
  }
  if (!shapes.length) {
    throw new Error(`vendor-phosphor: no path/circle/rect found in: ${svgSource}`);
  }
  return shapes;
}

function main() {
  const pkgDir = ensurePackage();
  const fillDir = path.join(pkgDir, 'assets/fill');
  const substituted = [];
  const shapesByName = {};

  for (const name of GRID) {
    const sourceName = SOURCE_NAME_OVERRIDES[name] || name;
    if (sourceName !== name) {
      substituted.push(`${name} -> ${sourceName}`);
    }
    const file = path.join(fillDir, `${sourceName}-fill.svg`);
    if (!fs.existsSync(file)) {
      throw new Error(
          `vendor-phosphor: no ${sourceName}-fill.svg in ` +
          `@phosphor-icons/core@${PHOSPHOR_VERSION} - add an entry to ` +
          'SOURCE_NAME_OVERRIDES for the closest existing glyph.');
    }
    shapesByName[name] = parseShapeChildren(fs.readFileSync(file, 'utf8'));
  }

  fs.mkdirSync(OUT_DIR, {recursive: true});

  const namesLiteral = GRID.map((n) => `  '${n}',`).join('\n');
  const shapesLiteral = GRID
      .map((name) => {
        const entries = shapesByName[name]
            .map(([tag, attrs]) => {
              const attrsLiteral = Object.entries(attrs)
                  .map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`)
                  .join(', ');
              return `[${JSON.stringify(tag)}, {${attrsLiteral}}]`;
            })
            .join(', ');
        return `  ${JSON.stringify(name)}: [${entries}],`;
      })
      .join('\n');

  const header = `// Copyright 2026 The Atrium Authors
// Use of this source code is governed by the Apache License, Version 2.0
// found in the LICENSE file.
// Generated by vendor-phosphor.mjs from @phosphor-icons/core ${PHOSPHOR_VERSION} (MIT, see ./LICENSE) - do not hand-edit.
`;

  const body = `
// The icon grid's slots, in render order.
export const PHOSPHOR_NAMES = [
${namesLiteral}
];

// name -> [[tag, attrs], ...] child nodes for the 256x256 fill glyph.
export const PHOSPHOR_SHAPES = {
${shapesLiteral}
};
`;

  fs.writeFileSync(path.join(OUT_DIR, 'fill.js'), header + body);
  fs.copyFileSync(
      path.join(pkgDir, 'LICENSE'), path.join(OUT_DIR, 'LICENSE'));

  console.log(`vendored ${GRID.length} glyphs from phosphor-icons/core@${PHOSPHOR_VERSION}`);
  console.log(substituted.length
      ? `substitutions: ${substituted.join(', ')}`
      : 'substitutions: none');
}

main();
