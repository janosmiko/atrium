//! The chrome layer's design tokens, as CSS custom properties.
//!
//! Ported from `TokenExport.swift`, which the cut deletes.
//! This is the regeneration side.
//!
//! `build/generated/tokens.css` is the reference and a test holds this to it
//! byte for byte. The formatting is the part that goes wrong quietly: a
//! generator with every number right and the spacing wrong produces a file
//! that reads as correct and fails a comparison.
//!
//! Values are literals here rather than derived. They were Swift constants,
//! and after the cut this is where they live - the two-copies pattern the ABI
//! header and the crate already use, with a guard rather than trust.

/// `favoriteTileMinWidth` becomes `--atrium-favorite-tile-min-width`.
fn property_name(symbol: &str) -> String {
    let mut out = String::from("--atrium-");
    for c in symbol.chars() {
        if c.is_uppercase() {
            out.push('-');
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Two decimal places, `px`, and a whole number drops its fraction: `220px`,
/// never `220.0px`.
fn length_value(value: f64) -> String {
    let rounded = (value * 100.0).round() / 100.0;
    if rounded == rounded.round() {
        format!("{}px", rounded as i64)
    } else {
        format!("{rounded}px")
    }
}

/// Four decimal places, no unit.
fn scalar_value(value: f64) -> String {
    let rounded = (value * 10000.0).round() / 10000.0;
    if rounded == rounded.round() {
        format!("{}", rounded as i64)
    } else {
        format!("{rounded}")
    }
}

/// Four decimal places and `s`, WITH the unit - CSS rejects a bare number for
/// a duration, and a JS caller parses it back by the same suffix.
fn duration_value(value: f64) -> String {
    let rounded = (value * 10000.0).round() / 10000.0;
    if rounded == rounded.round() {
        format!("{}s", rounded as i64)
    } else {
        format!("{rounded}s")
    }
}

