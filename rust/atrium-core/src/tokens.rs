/// The whole stylesheet.
pub fn css() -> String {
    // The license header is emitted, not added afterwards by hand. The WebUI copy
    // carried one and the generated reference did not, so verify-tokens.sh
    // reported drift on every run and make webui-test failed for everyone.
    //
    // The old source-of-truth line named SidebarMetrics.swift, TintPalette.swift,
    // ThemeMath.swift, PillTiming.swift and TokenExportTests. All five went with
    // the Swift package; the values live in this file now.
    let mut out = String::from(
        "/*\n * Copyright 2026 The Atrium Authors\n \
         * Use of this source code is governed by the Apache License, Version 2.0\n \
         * found in the LICENSE file.\n */\n\
         /* GENERATED by tokens::css() - do not edit.\n   \
         Regenerate: make tokens\n   \
         Source of truth: the tables in rust/atrium-core/src/tokens.rs.\n   \
         Drift is caught by verify-tokens.sh, not by review. */\n\n:root {\n",
    );

    out.push_str("  /* lengths */\n");
    for (symbol, value) in LENGTHS {
        out.push_str(&format!(
            "  {}: {};\n",
            property_name(symbol),
            length_value(*value)
        ));
    }
    out.push_str("\n  /* durations */\n");
    for (symbol, value) in DURATIONS {
        out.push_str(&format!(
            "  {}: {};\n",
            property_name(symbol),
            duration_value(*value)
        ));
    }
    out.push_str("\n  /* scalars */\n");
    for (symbol, value) in SCALARS {
        out.push_str(&format!(
            "  {}: {};\n",
            property_name(symbol),
            scalar_value(*value)
        ));
    }
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_symbol_becomes_a_kebab_property() {
        assert_eq!(
            property_name("favoriteTileMinWidth"),
            "--atrium-favorite-tile-min-width"
        );
        assert_eq!(property_name("width"), "--atrium-width");
    }

    /// The formatting is what goes wrong quietly. A whole number keeps no
    /// fraction, and only durations carry a unit that is not px.
    #[test]
    fn a_whole_number_drops_its_fraction() {
        assert_eq!(length_value(220.0), "220px");
        assert_eq!(length_value(13.5), "13.5px");
        assert_eq!(scalar_value(1.0), "1");
        assert_eq!(scalar_value(0.55), "0.55");
        assert_eq!(duration_value(3.0), "3s");
        assert_eq!(duration_value(0.2), "0.2s");
    }

    #[test]
    fn the_sections_are_lengths_then_durations_then_scalars() {
        let out = css();
        let lengths = out.find("/* lengths */").unwrap();
        let durations = out.find("/* durations */").unwrap();
        let scalars = out.find("/* scalars */").unwrap();
        assert!(lengths < durations && durations < scalars);
    }

    #[test]
    fn every_token_is_emitted() {
        let out = css();
        assert_eq!(
            out.matches("--atrium-").count(),
            LENGTHS.len() + DURATIONS.len() + SCALARS.len()
        );
    }
}
